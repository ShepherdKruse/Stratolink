#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "crypto_aes128.h"

static void expect_equal(const uint8_t actual[16], const uint8_t expected[16]) {
    assert(memcmp(actual, expected, 16) == 0);
}

int main(void) {
    const uint8_t aes_key[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
    };
    const uint8_t plaintext[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff,
    };
    const uint8_t ciphertext[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a,
    };
    uint8_t out[16];
    aes128_encrypt_block(aes_key, plaintext, out);
    expect_equal(out, ciphertext);

    const uint8_t cmac_key[16] = {
        0x2b,0x7e,0x15,0x16,0x28,0xae,0xd2,0xa6,
        0xab,0xf7,0x15,0x88,0x09,0xcf,0x4f,0x3c,
    };
    const uint8_t message[64] = {
        0x6b,0xc1,0xbe,0xe2,0x2e,0x40,0x9f,0x96,
        0xe9,0x3d,0x7e,0x11,0x73,0x93,0x17,0x2a,
        0xae,0x2d,0x8a,0x57,0x1e,0x03,0xac,0x9c,
        0x9e,0xb7,0x6f,0xac,0x45,0xaf,0x8e,0x51,
        0x30,0xc8,0x1c,0x46,0xa3,0x5c,0xe4,0x11,
        0xe5,0xfb,0xc1,0x19,0x1a,0x0a,0x52,0xef,
        0xf6,0x9f,0x24,0x45,0xdf,0x4f,0x9b,0x17,
        0xad,0x2b,0x41,0x7b,0xe6,0x6c,0x37,0x10,
    };
    const uint8_t expected[4][16] = {
        {0xbb,0x1d,0x69,0x29,0xe9,0x59,0x37,0x28,
         0x7f,0xa3,0x7d,0x12,0x9b,0x75,0x67,0x46},
        {0x07,0x0a,0x16,0xb4,0x6b,0x4d,0x41,0x44,
         0xf7,0x9b,0xdd,0x9d,0xd0,0x4a,0x28,0x7c},
        {0xdf,0xa6,0x67,0x47,0xde,0x9a,0xe6,0x30,
         0x30,0xca,0x32,0x61,0x14,0x97,0xc8,0x27},
        {0x51,0xf0,0xbe,0xbf,0x7e,0x3b,0x9d,0x92,
         0xfc,0x49,0x74,0x17,0x79,0x36,0x3c,0xfe},
    };
    const size_t lengths[] = {0, 16, 40, 64};
    for (int i = 0; i < 4; ++i) {
        const uint8_t* input = lengths[i] ? message : nullptr;
        assert(aes128_cmac(cmac_key, input, lengths[i], out));
        expect_equal(out, expected[i]);
    }
    assert(!aes128_cmac(nullptr, message, 16, out));
    assert(!aes128_cmac(cmac_key, nullptr, 1, out));
    assert(!aes128_cmac(cmac_key, message, 16, nullptr));

    uint8_t maximum[AES128_CMAC_MAX_BYTES] = {};
    assert(aes128_cmac(cmac_key, maximum, sizeof(maximum), out));
    assert(!aes128_cmac(
        cmac_key, maximum, AES128_CMAC_MAX_BYTES + 1u, out));
    assert(!aes128_cmac(cmac_key, maximum, SIZE_MAX, out));

    puts("AES-128/FIPS block and RFC 4493 CMAC vectors passed");
    return 0;
}
